/**
 * Switch page language
 */
function switchLanguage(lang) {
  if (!translations[lang]) return;

  // Set document lang
  document.documentElement.lang = lang;

  // Save preference
  try {
    localStorage.setItem('betalink_lang', lang);
  } catch (e) {}

  // Update language buttons active class
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  const t = translations[lang];

  // Update page title
  if (t.pageTitle) document.title = t.pageTitle;

  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  // Update elements with data-i18n-html
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key]) {
      el.innerHTML = t[key];
    }
  });

  // Update input placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) {
      el.placeholder = t[key];
    }
  });

  // Dispatch custom event for dynamic components (like territory radar & case study modal)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, t } }));
}

// Auto-init language on load
document.addEventListener('DOMContentLoaded', () => {
  let savedLang = 'it';
  try {
    savedLang = localStorage.getItem('betalink_lang') || 'it';
  } catch (e) {}

  // Bind clicks to language switch buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = btn.getAttribute('data-lang');
      switchLanguage(lang);
    });
  });

  // Apply initial language
  if (savedLang !== 'it') {
    switchLanguage(savedLang);
  }
});
